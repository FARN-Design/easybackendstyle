#!/usr/bin/env python3
"""Build the shipped scheme from a reviewed WordPress source, never at runtime."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'build/admin-colors'


def build(source, manifest):
    if hashlib.sha256(source).hexdigest() != manifest['sha256']:
        raise ValueError('WordPress CSS changed: review selectors, colors and source.json before building.')
    css = re.sub(r'/\*.*?\*/', '', source.decode(), flags=re.S)
    colors = manifest['colors']
    literals = set(re.findall(r'#[0-9a-fA-F]{3,8}\b|(?:rgb|hsl)\([\d.% ,]+\)', css))
    unknown = literals - set(colors) - set(manifest['unchanged_colors'])
    missing = set(colors) - literals
    if unknown or missing:
        raise ValueError(f'Unreviewed colors: {unknown}; missing mapped colors: {missing}')

    # Assign text colors by semantic context before generic palette replacement.
    def rule(match):
        selectors, declarations = match.groups()
        if '.button-primary' in selectors:
            declarations = re.sub(r'(?<![\w-])color:\s*#fff;', 'color: var(--ebsPrimaryButtonText);', declarations)
        elif '#adminmenu' in selectors and any(x in selectors for x in (':hover', ':focus', '.current', '.wp-has-current-submenu', '.awaiting-mod', '.update-plugins')):
            declarations = re.sub(r'(?<![\w-])color:\s*#(?:fff|1e1e1e);', 'color: var(--ebsHighlightedText);', declarations)
        # Modern uses one blue for links, selection and notifications; retain
        # independent controls by assigning those roles before literal replacement.
        if any(token in selectors for token in ('.awaiting-mod', '.update-plugins', '.menu-counter', '.wp-ui-notification', '.wp-ui-text-notification')):
            declarations = declarations.replace('#3858e9', 'var(--ebsNotification)')
        elif any(token in selectors for token in ('#adminmenu', '#collapse-button', '.wp-ui-highlight', '.wp-ui-text-highlight')):
            declarations = declarations.replace('#3858e9', 'var(--ebsTertiary)')
        return selectors + '{' + declarations + '}'
    css = re.sub(r'([^{}]+)\{([^{}]*)\}', rule, css)
    pattern = '|'.join(re.escape(c) for c in sorted(colors, key=len, reverse=True))
    css = re.sub(pattern + r'(?![\da-fA-F])', lambda m: 'var(--' + colors[m.group()] + ')', css)
    for suffix, key in [('', 'ebsPrimary'), ('-darker-10', 'ebsPrimaryDarker10'), ('-darker-20', 'ebsPrimaryDarker20')]:
        css = css.replace('var(--wp-admin-theme-color'+suffix+')', 'var(--'+key+')')
        css = css.replace('var(--wp-admin-theme-color'+suffix+'--rgb)', 'var(--'+key+'RGB)')
    # Outline and text buttons use readable text accents, not the fill color.
    def text_button(match):
        selectors, declarations = match.groups()
        if '.button' in selectors and '.button-primary' not in selectors and '.is-primary' not in selectors:
            declarations = re.sub(
                r'(?<![\w-])(color|border-color): var\(--ebsPrimary(Darker10|Darker20)?\);',
                lambda m: m[1] + ': var(--' + ('ebsLinksHover' if m[2] else 'ebsLinks') + ');', declarations)
            declarations = declarations.replace('border: 1px solid var(--ebsPrimary)', 'border: 1px solid var(--ebsLinks)')
        return selectors + '{' + declarations + '}'
    css = re.sub(r'([^{}]+)\{([^{}]*)\}', text_button, css)
    css = '\n'.join(line.rstrip() for line in css.splitlines())
    aliases = ('body.admin-color-personalizedcolorscheme,\n'
               'body.admin-color-personalizedcolorscheme .editor-editor-interface,\n'
               'body.admin-color-personalizedcolorscheme .components-button {\n')
    for suffix, key in [('', 'ebsPrimary'), ('-darker-10', 'ebsPrimaryDarker10'), ('-darker-20', 'ebsPrimaryDarker20')]:
        aliases += f'  --wp-admin-theme-color{suffix}: var(--{key});\n'
        aliases += f'  --wp-admin-theme-color{suffix}--rgb: var(--{key}RGB);\n'
    for suffix, key in [('', 'ebsPrimary'), ('-darker-10', 'ebsPrimaryDarker10'), ('-darker-20', 'ebsPrimaryDarker20'), ('-inverted', 'ebsPrimaryButtonText')]:
        aliases += f'  --wp-components-color-accent{suffix}: var(--{key});\n'
    aliases += '}\n'
    return (f'/* Generated by scripts/build-admin-colors.py. Do not edit.\n'
            f' * WordPress {manifest["wordpress"]} modern scheme; {manifest["license"]}.\n'
            f' * Source SHA-256: {manifest["sha256"]}\n */\n' + aliases + css.strip() + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--wordpress-root', type=Path, help='Fail if an installed WordPress source differs from the reviewed baseline.')
    args = parser.parse_args()
    manifest = json.loads((SOURCE / 'source.json').read_text())
    source = (SOURCE / 'modern.css').read_bytes()
    if args.wordpress_root and (args.wordpress_root / manifest['path']).read_bytes() != source:
        raise SystemExit('WordPress modern CSS differs from the reviewed baseline. Review before updating the preset.')
    generated = build(source, manifest)
    target = ROOT / 'resources/ebsMainCSS.css'
    if args.check:
        if target.read_text() != generated:
            raise SystemExit('Generated CSS is stale. Run npm run build:colors.')
    else:
        target.write_text(generated)
    print('Admin color scheme verified.' if args.check else 'Admin color scheme built.')


if __name__ == '__main__':
    main()
